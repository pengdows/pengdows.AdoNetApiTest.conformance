using System;
using System.Collections.Generic;
using System.Data;
using System.Linq;

namespace pengdows.AdoNetApiTest.conformance.Databases;

/// <summary>
/// The Oracle types and the values that show whether a provider keeps them intact. The expected values are what the
/// database stores and a correct provider returns. Oracle's own rules are written into the expectation: an empty string
/// is NULL, a <c>CHAR(10)</c> comes back padded and a <c>DATE</c> keeps whole seconds.
/// </summary>
public static class OracleTypes
{
	private const string AsText = "TO_CHAR({0})";

	public static IReadOnlyList<TypeSpec> Types { get; } = Build();

	public static IReadOnlyList<UncoveredType> UncoveredTypes { get; } = new[]
	{
		new UncoveredType("INTERVAL YEAR TO MONTH", "no CLR type holds a span of months"),
		new UncoveredType("TIMESTAMP WITH LOCAL TIME ZONE", "the value read back follows the session time zone"),
		new UncoveredType("XMLTYPE", "needs the provider's own type"),
		new UncoveredType("JSON", "the provider's JSON support is a separate capability"),
		new UncoveredType("VECTOR", "needs the provider's own type"),
		new UncoveredType("ROWID", "generated by the database"),
		new UncoveredType("UROWID", "generated by the database"),
		new UncoveredType("BFILE", "points at a file outside the database"),
		new UncoveredType("FLOAT", "a NUMBER with binary precision, covered by NUMBER"),
	};

	public static string ParameterMarker(string name) => ":" + name;

	public static string CreateTableSql(string table, string columnSql) =>
		$"create table {table} (Id NUMBER(10) not null primary key, V {columnSql} null)";

	public static string DropTableSql(string table) => $"drop table if exists {table}";

	private static TypeValue V(string label, string literal, object expected) => new TypeValue(label, literal, expected);

	private static TypeValue Null() => V("null", "NULL", null);

	private static IReadOnlyList<TypeSpec> Build()
	{
		var bytes = new byte[] { 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF };
		var longText = new string('x', 5000);

		return new List<TypeSpec>
		{
			new TypeSpec("NUMBER", "NUMBER(28,10)", typeof(decimal), DbType.Decimal,
				V("zero", "0", 0m), V("max", "999999999999999999.9999999999", 999999999999999999.9999999999m),
				V("smallest step", "0.0000000001", 0.0000000001m), V("negative", "-12345.6789", -12345.6789m), Null()) { RenderAsText = AsText },
			// ODP.NET bound DbType.Double as NUMBER, so a double beyond NUMBER's 1e126 overflowed on bind (pengdows.crud TYPE-002).
			new TypeSpec("BINARY_DOUBLE", "BINARY_DOUBLE", typeof(double), DbType.Double,
				V("zero", "0d", 0d), V("0.1", "0.1d", 0.1), V("1e200", "1e200d", 1e200), V("minus 1e200", "-1e200d", -1e200),
				V("max", "1.7976931348623157E+308d", double.MaxValue), V("min normal", "2.2250738585072014E-308d", 2.2250738585072014E-308), Null()) { RenderAsText = AsText },
			new TypeSpec("BINARY_FLOAT", "BINARY_FLOAT", typeof(float), DbType.Single,
				V("zero", "0f", 0f), V("one and a half", "1.5f", 1.5f), V("0.1", "0.1f", 0.1f), V("large", "3.4E+38f", 3.4E+38f), Null()) { RenderAsText = AsText },
			new TypeSpec("BOOLEAN", "BOOLEAN", typeof(bool), DbType.Boolean,
				V("true", "TRUE", true), V("false", "FALSE", false), Null()) { RenderAsText = AsText },

			new TypeSpec("VARCHAR2", "VARCHAR2(100 CHAR)", typeof(string), DbType.String,
				V("ascii", "'abc'", "abc"), V("quote", "'it''s'", "it's"), V("non-BMP", "'\U0001F600'", "\U0001F600"),
				V("empty is NULL", "''", null).Binding(string.Empty), Null()) { RenderAsText = AsText },
			new TypeSpec("NVARCHAR2", "NVARCHAR2(100)", typeof(string), DbType.String,
				V("ascii", "N'abc'", "abc"), V("cjk", "N'日本語'", "日本語"), Null()) { RenderAsText = AsText },
			new TypeSpec("CHAR", "CHAR(10 CHAR)", typeof(string), DbType.StringFixedLength,
				V("padded", "'abc'", "abc       ").Binding("abc"), V("full", "'abcdefghij'", "abcdefghij"), Null()) { RenderAsText = AsText },
			new TypeSpec("CLOB", "CLOB", typeof(string), DbType.String,
				V("ascii", "TO_CLOB('abc')", "abc"),
				V("5000 chars", "TO_CLOB(RPAD('x', 4000, 'x')) || RPAD('x', 1000, 'x')", longText), Null())
			{
				RenderAsText = "DBMS_LOB.SUBSTR({0}, 4000, 1)",
				Comparable = false,
			},
			// ODP.NET reads LONG as empty unless the select list has the row's key or ROWID, or InitialLONGFetchSize is -1
			// (pengdows.crud TYPE-002). The read here selects only the column. LONG cannot be converted to text in SQL.
			new TypeSpec("LONG", "LONG", typeof(string), DbType.String,
				V("ascii", "'abc'", "abc"), Null())
			{
				WriteOracle = false,
				Comparable = false,
			},

			new TypeSpec("RAW", "RAW(16)", typeof(byte[]), DbType.Binary,
				V("bytes", "HEXTORAW('00112233445566778899AABBCCDDEEFF')", bytes), Null()) { RenderAsText = "RAWTOHEX({0})" },
			new TypeSpec("BLOB", "BLOB", typeof(byte[]), DbType.Binary,
				V("bytes", "TO_BLOB(HEXTORAW('00112233445566778899AABBCCDDEEFF'))", bytes), Null())
			{
				RenderAsText = "RAWTOHEX(DBMS_LOB.SUBSTR({0}, 2000, 1))",
				Comparable = false,
			},
			new TypeSpec("LONG RAW", "LONG RAW", typeof(byte[]), DbType.Binary,
				V("bytes", "HEXTORAW('00112233445566778899AABBCCDDEEFF')", bytes), Null())
			{
				WriteOracle = false,
				Comparable = false,
			},

			new TypeSpec("DATE", "DATE", typeof(DateTime), DbType.DateTime,
				V("date and time", "TO_DATE('2024-02-29 12:34:56', 'YYYY-MM-DD HH24:MI:SS')", new DateTime(2024, 2, 29, 12, 34, 56)), Null())
			{
				RenderAsText = "TO_CHAR({0}, 'YYYY-MM-DD HH24:MI:SS')",
			},
			new TypeSpec("TIMESTAMP", "TIMESTAMP(6)", typeof(DateTime), DbType.DateTime,
				V("microseconds", "TIMESTAMP '2024-01-01 12:34:56.123456'", new DateTime(2024, 1, 1, 12, 34, 56).AddTicks(1234560)), Null())
			{
				RenderAsText = "TO_CHAR({0}, 'YYYY-MM-DD HH24:MI:SS.FF6')",
			},
			new TypeSpec("TIMESTAMP WITH TIME ZONE", "TIMESTAMP(6) WITH TIME ZONE", typeof(DateTimeOffset), DbType.DateTimeOffset,
				V("plus five hours", "TIMESTAMP '2024-01-01 12:00:00.000000 +05:00'", new DateTimeOffset(2024, 1, 1, 12, 0, 0, TimeSpan.FromHours(5))),
				V("utc", "TIMESTAMP '2024-01-01 07:00:00.000000 +00:00'", new DateTimeOffset(2024, 1, 1, 7, 0, 0, TimeSpan.Zero)), Null())
			{
				RenderAsText = "TO_CHAR({0}, 'YYYY-MM-DD HH24:MI:SS.FF6 TZH:TZM')",
			},
			new TypeSpec("INTERVAL DAY TO SECOND", "INTERVAL DAY(9) TO SECOND(6)", typeof(TimeSpan), DbType.Object,
				V("day and time", "INTERVAL '1 02:03:04.5' DAY TO SECOND", new TimeSpan(1, 2, 3, 4, 500)),
				V("negative", "INTERVAL '-0 02:00:00' DAY TO SECOND", TimeSpan.FromHours(-2)), Null()) { RenderAsText = AsText },
		};
	}
}
