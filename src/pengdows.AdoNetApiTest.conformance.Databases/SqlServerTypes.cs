using System;
using System.Collections.Generic;
using System.Data;
using System.Globalization;
using System.Linq;
using System.Text;

namespace pengdows.AdoNetApiTest.conformance.Databases;

/// <summary>
/// The SQL Server types and the values that show whether a provider keeps them intact. The expected values are what the
/// database stores and a correct provider returns: a <c>char(10)</c> comes back padded, a <c>datetime</c> keeps
/// 3.33 ms steps. Those are the database's rules, so they are written into the expectation and are never a driver bug.
/// </summary>
public static class SqlServerTypes
{
	private const string DateTimeStyle = "CONVERT(nvarchar(40), {0}, 126)";
	private const string HexStyle = "CONVERT(varchar(max), {0}, 1)";

	public static IReadOnlyList<TypeSpec> Types { get; } = Build();

	public static IReadOnlyList<UncoveredType> UncoveredTypes { get; } = new[]
	{
		new UncoveredType("sql_variant", "its CLR type is object and the stored value's own type decides what comes back"),
		new UncoveredType("timestamp", "rowversion is generated by the database and cannot be written"),
		new UncoveredType("hierarchyid", "needs Microsoft.SqlServer.Types"),
		new UncoveredType("geometry", "needs Microsoft.SqlServer.Types"),
		new UncoveredType("geography", "needs Microsoft.SqlServer.Types"),
	};

	public static string ParameterMarker(string name) => "@" + name;

	public static string CreateTableSql(string table, string columnSql) =>
		$"create table [{table}] (Id int not null primary key, V {columnSql} null)";

	public static string DropTableSql(string table) => $"drop table if exists [{table}]";

	private static TypeValue V(string label, string literal, object expected) => new TypeValue(label, literal, expected);

	private static TypeValue Null() => V("null", "NULL", null);

	private static IReadOnlyList<TypeSpec> Build()
	{
		var allBytes = Enumerable.Range(0, 256).Select(i => (byte) i).ToArray();
		var allBytesHex = "0x" + string.Concat(allBytes.Select(b => b.ToString("X2", CultureInfo.InvariantCulture)));
		var ab = Enumerable.Repeat((byte) 0xAB, 8001).ToArray();
		var guid = new Guid("33221100-5544-7766-9988-aabbccddeeff");

		return new List<TypeSpec>
		{
			new TypeSpec("tinyint", "tinyint", typeof(byte), DbType.Byte,
				V("min", "CAST(0 AS tinyint)", (byte) 0), V("max", "CAST(255 AS tinyint)", (byte) 255), Null()),
			new TypeSpec("smallint", "smallint", typeof(short), DbType.Int16,
				V("min", "CAST(-32768 AS smallint)", short.MinValue), V("minus one", "CAST(-1 AS smallint)", (short) -1),
				V("zero", "CAST(0 AS smallint)", (short) 0), V("max", "CAST(32767 AS smallint)", short.MaxValue), Null()),
			new TypeSpec("int", "int", typeof(int), DbType.Int32,
				V("min", "-2147483648", int.MinValue), V("minus one", "-1", -1), V("zero", "0", 0), V("max", "2147483647", int.MaxValue), Null()),
			new TypeSpec("bigint", "bigint", typeof(long), DbType.Int64,
				V("min", "CAST(-9223372036854775808 AS bigint)", long.MinValue), V("minus one", "CAST(-1 AS bigint)", -1L),
				V("zero", "CAST(0 AS bigint)", 0L), V("max", "CAST(9223372036854775807 AS bigint)", long.MaxValue), Null()),
			new TypeSpec("bit", "bit", typeof(bool), DbType.Boolean,
				V("true", "CAST(1 AS bit)", true), V("false", "CAST(0 AS bit)", false), Null()),

			new TypeSpec("real", "real", typeof(float), DbType.Single,
				V("zero", "CAST(0 AS real)", 0f), V("one and a half", "CAST(1.5 AS real)", 1.5f), V("minus one and a half", "CAST(-1.5 AS real)", -1.5f),
				V("0.1", "CAST(0.1 AS real)", 0.1f), V("large", "CAST(3.4E+38 AS real)", 3.4E+38f), V("small", "CAST(1.18E-38 AS real)", 1.18E-38f), Null())
			{
				RenderAsText = "CONVERT(varchar(max), CAST({0} AS binary(4)), 1)",
			},
			new TypeSpec("float", "float", typeof(double), DbType.Double,
				V("zero", "CAST(0 AS float)", 0d), V("one and a half", "CAST(1.5 AS float)", 1.5), V("minus one and a half", "CAST(-1.5 AS float)", -1.5),
				V("0.1", "CAST(0.1 AS float)", 0.1), V("max", "CAST(1.7976931348623157E+308 AS float)", double.MaxValue),
				V("min normal", "CAST(2.2250738585072014E-308 AS float)", 2.2250738585072014E-308), Null())
			{
				RenderAsText = "CONVERT(varchar(max), CAST({0} AS binary(8)), 1)",
			},

			new TypeSpec("decimal", "decimal(18,4)", typeof(decimal), DbType.Decimal,
				V("zero", "CAST(0 AS decimal(18,4))", 0m), V("max", "CAST('99999999999999.9999' AS decimal(18,4))", 99999999999999.9999m),
				V("min", "CAST('-99999999999999.9999' AS decimal(18,4))", -99999999999999.9999m), V("smallest step", "CAST('0.0001' AS decimal(18,4))", 0.0001m),
				V("one and a half", "CAST('1.5' AS decimal(18,4))", 1.5m), Null())
			{
				Precision = 18,
				Scale = 4,
			},
			new TypeSpec("decimal", "decimal(28,10)", typeof(decimal), DbType.Decimal,
				V("max", "CAST('999999999999999999.9999999999' AS decimal(28,10))", 999999999999999999.9999999999m),
				V("smallest step", "CAST('0.0000000001' AS decimal(28,10))", 0.0000000001m),
				V("min", "CAST('-999999999999999999.9999999999' AS decimal(28,10))", -999999999999999999.9999999999m), Null())
			{
				Precision = 28,
				Scale = 10,
			},
			new TypeSpec("numeric", "numeric(10,2)", typeof(decimal), DbType.Decimal,
				V("max", "CAST('99999999.99' AS numeric(10,2))", 99999999.99m), V("minus", "CAST('-0.01' AS numeric(10,2))", -0.01m), Null())
			{
				Precision = 10,
				Scale = 2,
			},
			new TypeSpec("money", "money", typeof(decimal), DbType.Currency,
				V("min", "CAST('-922337203685477.5808' AS money)", -922337203685477.5808m), V("max", "CAST('922337203685477.5807' AS money)", 922337203685477.5807m),
				V("smallest step", "CAST('0.0001' AS money)", 0.0001m), V("zero", "CAST(0 AS money)", 0m), Null())
			{
				RenderAsText = "CONVERT(nvarchar(max), {0}, 2)",
			},
			new TypeSpec("smallmoney", "smallmoney", typeof(decimal), DbType.Currency,
				V("min", "CAST('-214748.3648' AS smallmoney)", -214748.3648m), V("max", "CAST('214748.3647' AS smallmoney)", 214748.3647m), Null())
			{
				RenderAsText = "CONVERT(nvarchar(max), {0}, 2)",
			},

			new TypeSpec("char", "char(10)", typeof(string), DbType.AnsiStringFixedLength,
				V("padded", "'abc'", "abc       ").Binding("abc"), V("full", "'abcdefghij'", "abcdefghij"), V("empty", "''", "          ").Binding(string.Empty), Null())
			{
				Size = 10,
			},
			new TypeSpec("varchar", "varchar(50)", typeof(string), DbType.AnsiString,
				V("empty", "''", string.Empty), V("ascii", "'abc'", "abc"), V("latin1", "'café'", "café"),
				V("quote and backslash", "'it''s \\ \"q\"'", "it's \\ \"q\""), V("trailing spaces", "'abc  '", "abc  "),
				V("full", "REPLICATE('x', 50)", new string('x', 50)), Null())
			{
				Size = 50,
			},
			new TypeSpec("varchar", "varchar(max)", typeof(string), DbType.AnsiString,
				V("empty", "''", string.Empty), V("long", "REPLICATE(CAST('x' AS varchar(max)), 10000)", new string('x', 10000)), Null())
			{
				Size = -1,
			},
			new TypeSpec("nchar", "nchar(10)", typeof(string), DbType.StringFixedLength,
				V("padded", "N'abc'", "abc       ").Binding("abc"), V("cjk", "N'日本語'", "日本語       ").Binding("日本語"), Null())
			{
				Size = 10,
			},
			new TypeSpec("nvarchar", "nvarchar(50)", typeof(string), DbType.String,
				V("empty", "N''", string.Empty), V("latin", "N'héllo wörld'", "héllo wörld"), V("cjk", "N'日本語'", "日本語"),
				V("non-BMP", "N'\U0001F600'", "\U0001F600"), V("trailing spaces", "N'abc  '", "abc  "),
				V("quote and backslash", "N'it''s \\ \"q\"'", "it's \\ \"q\""), V("embedded NUL", "N'a' + NCHAR(0) + N'b'", "a\0b"),
				V("full", "REPLICATE(N'x', 50)", new string('x', 50)), Null())
			{
				Size = 50,
			},
			new TypeSpec("nvarchar", "nvarchar(max)", typeof(string), DbType.String,
				V("empty", "N''", string.Empty), V("long", "REPLICATE(CAST(N'x' AS nvarchar(max)), 10000)", new string('x', 10000)),
				V("non-BMP", "N'\U0001F600'", "\U0001F600"), Null())
			{
				Size = -1,
			},
			new TypeSpec("text", "text", typeof(string), DbType.AnsiString,
				V("ascii", "'abc'", "abc"), Null())
			{
				Size = -1,
				Comparable = false,
				RenderAsText = "CAST(CAST({0} AS varchar(max)) AS nvarchar(max))",
			},
			new TypeSpec("ntext", "ntext", typeof(string), DbType.String,
				V("latin", "N'héllo'", "héllo"), Null())
			{
				Size = -1,
				Comparable = false,
				RenderAsText = "CAST(CAST({0} AS nvarchar(max)) AS nvarchar(max))",
			},
			new TypeSpec("xml", "xml", typeof(string), DbType.Xml,
				V("element", "CAST('<a>1</a>' AS xml)", "<a>1</a>"), Null())
			{
				Comparable = false,
			},

			new TypeSpec("binary", "binary(4)", typeof(byte[]), DbType.Binary,
				V("full", "CAST(0x01020304 AS binary(4))", new byte[] { 1, 2, 3, 4 }),
				V("padded", "CAST(0x0102 AS binary(4))", new byte[] { 1, 2, 0, 0 }).Binding(new byte[] { 1, 2 }), Null())
			{
				Size = 4,
				RenderAsText = HexStyle,
			},
			new TypeSpec("varbinary", "varbinary(50)", typeof(byte[]), DbType.Binary,
				V("empty", "0x", new byte[0]), V("one zero byte", "0x00", new byte[] { 0 }), V("high bytes", "0xFFFE", new byte[] { 0xFF, 0xFE }), Null())
			{
				Size = 50,
				RenderAsText = HexStyle,
			},
			new TypeSpec("varbinary", "varbinary(max)", typeof(byte[]), DbType.Binary,
				V("empty", "0x", new byte[0]), V("every byte value", allBytesHex, allBytes),
				V("beyond 8000 bytes", "CONVERT(varbinary(max), REPLICATE(CAST('AB' AS varchar(max)), 8001), 2)", ab), Null())
			{
				Size = -1,
				RenderAsText = HexStyle,
			},
			new TypeSpec("image", "image", typeof(byte[]), DbType.Binary,
				V("bytes", "0x0102", new byte[] { 1, 2 }), Null())
			{
				Size = -1,
				Comparable = false,
				RenderAsText = "CONVERT(varchar(max), CAST({0} AS varbinary(max)), 1)",
			},

			new TypeSpec("uniqueidentifier", "uniqueidentifier", typeof(Guid), DbType.Guid,
				V("empty", "CAST('00000000-0000-0000-0000-000000000000' AS uniqueidentifier)", Guid.Empty),
				V("mixed bytes", "CAST('33221100-5544-7766-9988-AABBCCDDEEFF' AS uniqueidentifier)", guid),
				V("all F", "CAST('FFFFFFFF-FFFF-FFFF-FFFF-FFFFFFFFFFFF' AS uniqueidentifier)", new Guid("FFFFFFFF-FFFF-FFFF-FFFF-FFFFFFFFFFFF")), Null()),

			new TypeSpec("date", "date", typeof(DateTime), DbType.Date,
				V("min", "CAST('0001-01-01' AS date)", new DateTime(1, 1, 1)), V("max", "CAST('9999-12-31' AS date)", new DateTime(9999, 12, 31)),
				V("leap day", "CAST('2020-02-29' AS date)", new DateTime(2020, 2, 29)), Null())
			{
				RenderAsText = DateTimeStyle,
			},
			new TypeSpec("time", "time(7)", typeof(TimeSpan), DbType.Time,
				V("midnight", "CAST('00:00:00' AS time(7))", TimeSpan.Zero),
				V("max", "CAST('23:59:59.9999999' AS time(7))", TimeSpan.FromTicks(TimeSpan.TicksPerDay - 1)),
				V("100ns ticks", "CAST('12:34:56.1234567' AS time(7))", new TimeSpan(12, 34, 56).Add(TimeSpan.FromTicks(1234567))), Null())
			{
				Scale = 7,
			},
			new TypeSpec("datetime2", "datetime2(7)", typeof(DateTime), DbType.DateTime2,
				V("min", "CAST('0001-01-01T00:00:00' AS datetime2(7))", DateTime.MinValue),
				V("max", "CAST('9999-12-31T23:59:59.9999999' AS datetime2(7))", DateTime.MaxValue),
				V("100ns ticks", "CAST('2020-01-02T03:04:05.1234567' AS datetime2(7))", new DateTime(2020, 1, 2, 3, 4, 5).AddTicks(1234567)), Null())
			{
				Scale = 7,
				RenderAsText = DateTimeStyle,
			},
			new TypeSpec("datetime", "datetime", typeof(DateTime), DbType.DateTime,
				V("min", "CAST('1753-01-01T00:00:00' AS datetime)", new DateTime(1753, 1, 1)),
				V("max", "CAST('9999-12-31T23:59:59.997' AS datetime)", new DateTime(9999, 12, 31, 23, 59, 59, 997)),
				V("milliseconds", "CAST('2020-01-02T03:04:05.123' AS datetime)", new DateTime(2020, 1, 2, 3, 4, 5, 123)),
				V("rounds to 3.33 ms steps", "CAST('2020-01-02T03:04:05.123' AS datetime)", new DateTime(2020, 1, 2, 3, 4, 5, 123))
					.Binding(new DateTime(2020, 1, 2, 3, 4, 5).AddTicks(1234567)), Null())
			{
				RenderAsText = DateTimeStyle,
			},
			new TypeSpec("smalldatetime", "smalldatetime", typeof(DateTime), DbType.DateTime,
				V("min", "CAST('1900-01-01T00:00:00' AS smalldatetime)", new DateTime(1900, 1, 1)),
				V("max", "CAST('2079-06-06T23:59:00' AS smalldatetime)", new DateTime(2079, 6, 6, 23, 59, 0)),
				V("minute", "CAST('2020-01-02T03:04:00' AS smalldatetime)", new DateTime(2020, 1, 2, 3, 4, 0)), Null())
			{
				RenderAsText = DateTimeStyle,
			},
			new TypeSpec("datetimeoffset", "datetimeoffset(7)", typeof(DateTimeOffset), DbType.DateTimeOffset,
				V("min", "CAST('0001-01-01 00:00:00.0000000 +00:00' AS datetimeoffset(7))", DateTimeOffset.MinValue),
				V("max", "CAST('9999-12-31 23:59:59.9999999 +00:00' AS datetimeoffset(7))", DateTimeOffset.MaxValue),
				V("+05:30", "CAST('2020-01-02 03:04:05.1234567 +05:30' AS datetimeoffset(7))", new DateTimeOffset(new DateTime(2020, 1, 2, 3, 4, 5).AddTicks(1234567), TimeSpan.FromHours(5.5))),
				V("-08:00", "CAST('2020-01-02 03:04:05.1234567 -08:00' AS datetimeoffset(7))", new DateTimeOffset(new DateTime(2020, 1, 2, 3, 4, 5).AddTicks(1234567), TimeSpan.FromHours(-8))), Null())
			{
				Scale = 7,
				RenderAsText = "CONVERT(nvarchar(40), {0}, 127)",
			},
		};
	}
}
